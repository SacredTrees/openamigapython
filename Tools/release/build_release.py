#!/usr/bin/env python3
"""Build a reproducible OpenAmigaPython drawer and OpenUp Part."""

import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess


PATCHLEVEL_RE = {
    "base": re.compile(r'^#define\s+PY_VERSION_BASE\s+"([^"]+)"', re.M),
    "build": re.compile(r"^#define\s+AC_BUILD\s+(\d+)", re.M),
    "tag": re.compile(r'^#define\s+AC_BUILD_TAG\s+"([^"]+)"', re.M),
}


def parse_version(header):
    text = Path(header).read_text(encoding="ascii")
    values = {}
    for name, pattern in PATCHLEVEL_RE.items():
        match = pattern.search(text)
        if not match:
            raise ValueError("missing %s in %s" % (name, header))
        values[name] = match.group(1)
    if values["tag"] != "ac%s" % values["build"]:
        raise ValueError("AC_BUILD and AC_BUILD_TAG disagree")
    values["version"] = "%s-%s" % (values["base"], values["tag"])
    values["build"] = int(values["build"])
    return values


def sha256(path):
    digest = hashlib.sha256()
    with Path(path).open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def files_under(root):
    root = Path(root)
    result = []
    for path in sorted(root.rglob("*")):
        if path.is_symlink():
            raise ValueError("release payload may not contain symlinks: %s" % path)
        if path.is_file():
            result.append((path.relative_to(root).as_posix(), path))
    return result


def copy_tree(source, destination):
    source = Path(source)
    destination = Path(destination)
    for relative, path in files_under(source):
        target = destination / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(str(path), str(target))


def git_revision(root):
    return subprocess.check_output(
        ["git", "-C", str(root), "rev-parse", "HEAD"], text=True
    ).strip()


def require_clean_tree(root):
    changes = subprocess.check_output(
        ["git", "-C", str(root), "status", "--porcelain"], text=True
    ).strip()
    if changes:
        raise ValueError(
            "refusing to stamp a release from a dirty tree; commit the source "
            "or pass --allow-dirty for a non-published test build"
        )


def write_metadata(drawer, version, revision):
    drawer = Path(drawer)
    excluded = {"SHA256SUMS", "openamigapython-release.json"}
    entries = []
    for relative, path in files_under(drawer):
        if relative not in excluded:
            entries.append({
                "path": relative,
                "bytes": path.stat().st_size,
                "sha256": sha256(path),
            })
    metadata = {
        "schema": 1,
        "name": "OpenAmigaPython",
        "version": version["version"],
        "python_abi": "cp27-pyamiga9",
        "platform": "amigaos3_m68k_68020_softfloat",
        "source_commit": revision,
        "files": entries,
    }
    manifest = drawer / "openamigapython-release.json"
    manifest.write_text(
        json.dumps(metadata, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    sums = []
    for relative, path in files_under(drawer):
        if relative != "SHA256SUMS":
            sums.append("%s  %s" % (sha256(path), relative))
    (drawer / "SHA256SUMS").write_text("\n".join(sums) + "\n", encoding="ascii")
    return metadata


def quote_part(value):
    if '"' in value or "\n" in value or "\r" in value:
        raise ValueError("OpenUp path cannot contain quotes or newlines: %r" % value)
    return '"%s"' % value


def write_openup_part(drawer, part_dir, version):
    drawer = Path(drawer)
    part_dir = Path(part_dir)
    if part_dir.name != "OpenAmigaPython":
        raise ValueError("OpenUp Part directory must be named OpenAmigaPython")
    if part_dir.exists():
        shutil.rmtree(str(part_dir))
    payload = part_dir / "Payload"
    copy_tree(drawer, payload)
    destination = "SYS:Tools/OpenAmigaPython/%s" % version["version"]
    lines = [
        "part OpenAmigaPython %s" % version["version"],
        "; Generated by Tools/release/build_release.py",
        "; Versioned install with managed startup entries for safe upgrades.",
        "needs AmigaChrome",
    ]
    for relative, unused_path in files_under(payload):
        lines.append("copy %s %s" % (
            quote_part("Payload/%s" % relative),
            quote_part("%s/%s" % (destination, relative)),
        ))
    lines.extend((
        "startup Assign >NIL: Python: %s" % destination,
        "startup Path Python: ADD",
    ))
    part_dir.mkdir(parents=True, exist_ok=True)
    (part_dir / "Part").write_bytes(("\n".join(lines) + "\n").encode("latin-1"))


def build(args):
    root = Path(args.root).resolve()
    if not args.allow_dirty and not args.revision:
        require_clean_tree(root)
    version = parse_version(root / "Source/Include/patchlevel.h")
    binary = Path(args.binary or root / "Source/Python27")
    stdlib = Path(args.stdlib or root / "Source/lib/python27.zip")
    for required in (binary, stdlib):
        if not required.is_file():
            raise ValueError("missing release input: %s" % required)

    output_root = Path(args.output or root / "dist/staging")
    drawer = output_root / ("OpenAmigaPython-%s" % version["version"])
    if drawer.exists():
        shutil.rmtree(str(drawer))
    copy_tree(root / "Python", drawer)
    shutil.copyfile(str(binary), str(drawer / "Python"))
    lib_dir = drawer / "lib"
    lib_dir.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(str(stdlib), str(lib_dir / "python27.zip"))
    revision = args.revision or git_revision(root)
    write_metadata(drawer, version, revision)

    part_dir = Path(args.openup_part or output_root / "OpenUp/Parts/OpenAmigaPython")
    write_openup_part(drawer, part_dir, version)
    print("release drawer: %s" % drawer)
    print("OpenUp Part: %s" % part_dir)
    return 0


def parser():
    result = argparse.ArgumentParser(description=__doc__)
    result.add_argument("--root", default=Path(__file__).resolve().parents[2])
    result.add_argument("--binary")
    result.add_argument("--stdlib")
    result.add_argument("--output")
    result.add_argument("--openup-part")
    result.add_argument("--revision")
    result.add_argument("--allow-dirty", action="store_true")
    return result


if __name__ == "__main__":
    raise SystemExit(build(parser().parse_args()))

